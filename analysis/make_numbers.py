"""Write analysis/numbers.tex: one \\newcommand per number, read only from analysis/out/*_endpoints.csv.

Usage: python analysis/make_numbers.py [--out-dir analysis/out] [--tex analysis/numbers.tex]
Macro name = set + endpoint + method + stratum + what + suffix, letters only (digits spelled out),
e.g. \\PHundredPOneGmresAllPassRate. Suffixes: K, N, Rate (percent, 1 decimal), Lo, Hi (percent),
Excl. For S1 rows the value (median) is written as a plain number with Value, Lo, Hi.
"""
import argparse
import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WORDS = {'0': 'Zero', '1': 'One', '2': 'Two', '3': 'Three', '4': 'Four', '5': 'Five',
         '6': 'Six', '7': 'Seven', '8': 'Eight', '9': 'Nine'}


def alpha(text):
    s = ''.join(WORDS.get(c, c) for c in text)
    return ''.join(p[:1].upper() + p[1:] for p in re.split(r'[^A-Za-z]+', s) if p)


def fmt_pct(x):
    return '%.1f' % (100 * float(x))


def macros(csv_path):
    prefix = alpha(Path(csv_path).stem.replace('_endpoints', ''))
    for r in csv.DictReader(open(csv_path)):
        base = prefix + alpha(r['endpoint']) + alpha(r['method']) + alpha(r['stratum']) + alpha(r['what'])
        yield base + 'N', r['n']
        if r['endpoint'] == 'S1':
            yield base + 'Value', '%.4g' % float(r['rate'])
            yield base + 'Lo', '%.4g' % float(r['lo'])
            yield base + 'Hi', '%.4g' % float(r['hi'])
        else:
            yield base + 'K', r['k']
            yield base + 'Rate', fmt_pct(r['rate'])
            yield base + 'Lo', fmt_pct(r['lo'])
            yield base + 'Hi', fmt_pct(r['hi'])
            yield base + 'Excl', r['excluded']


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out-dir', default=str(ROOT / 'analysis' / 'out'))
    ap.add_argument('--tex', default=str(ROOT / 'analysis' / 'numbers.tex'))
    a = ap.parse_args()
    files = sorted(Path(a.out_dir).glob('*_endpoints.csv'))
    lines = ['% Generated by analysis/make_numbers.py from: ' + ', '.join(f.name for f in files)]
    seen = set()
    for f in files:
        for name, val in macros(f):
            assert name not in seen, 'duplicate macro ' + name
            seen.add(name)
            lines.append('\\newcommand{\\%s}{%s}' % (name, val))
    Path(a.tex).write_text('\n'.join(lines) + '\n')
    print('wrote', a.tex, len(seen), 'macros from', len(files), 'files')


if __name__ == '__main__':
    main()
