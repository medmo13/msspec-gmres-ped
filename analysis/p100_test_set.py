"""Describe the P100 test set (100 materials) from platform/materials_v2.csv.

Writes figures/p100_test_set.png (the figure) and manuscript/numbers_p100.tex (macros the
article reads). Every number in the article about the test set comes from this script.
Usage: python analysis/p100_test_set.py
"""
import csv
from pathlib import Path
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parents[1]
ROWS = list(csv.DictReader(open(ROOT / 'platform' / 'materials_v2.csv')))
HIGH = [r for r in ROWS if r['stratum'] == 'high']
LOW = [r for r in ROWS if r['stratum'] == 'low']
WORDS = dict(zip('0123456789', ['Zero', 'One', 'Two', 'Three', 'Four', 'Five', 'Six', 'Seven', 'Eight', 'Nine']))


def col(rs, k):
    return np.array([float(r[k]) for r in rs])


def macro(name, value):
    name = name.replace('P100', 'PHundred')
    return '\\newcommand{\\%s}{%s}' % (name, value)


def numbers():
    out = ['% Generated by analysis/p100_test_set.py from platform/materials_v2.csv. Do not edit.']
    for tag, rs in [('All', ROWS), ('High', HIGH), ('Low', LOW)]:
        out.append(macro('P100Cases' + tag, len(rs)))
        out.append(macro('P100Materials' + tag, len({r['name'] for r in rs})))
        out.append(macro('P100Structures' + tag, len({r['prototype'] for r in rs})))
        out.append(macro('P100RhoMin' + tag, '%.2f' % col(rs, 'rho').min()))
        out.append(macro('P100RhoMax' + tag, '%.2f' % col(rs, 'rho').max()))
        out.append(macro('P100KeMedian' + tag, '%.0f' % np.median(col(rs, 'ke'))))
        out.append(macro('P100KeMin' + tag, '%.0f' % col(rs, 'ke').min()))
        out.append(macro('P100KeMax' + tag, '%.0f' % col(rs, 'ke').max()))
        out.append(macro('P100AtomsMin' + tag, '%d' % col(rs, 'natoms').min()))
        out.append(macro('P100AtomsMax' + tag, '%d' % col(rs, 'natoms').max()))
        out.append(macro('P100AtomsMedian' + tag, '%.0f' % np.median(col(rs, 'natoms'))))
    out.append(macro('P100LevelsAll', len({r['level'] for r in ROWS})))
    out.append(macro('P100RhoGapCount', sum(1 for r in ROWS if 1.0 <= float(r['rho']) < 1.2)))
    return out


def figure(path):
    ch, cl = '#d62728', '#1f77b4'
    fig, ax = plt.subplots(1, 3, figsize=(15, 4.6))
    a = ax[0]
    b = np.linspace(0, 3.4, 18)
    a.hist(col(LOW, 'rho'), b, color=cl, alpha=.85, label='low (rho < 1)')
    a.hist(col(HIGH, 'rho'), b, color=ch, alpha=.85, label='high (rho >= 1.2)')
    a.axvline(1, color='k', ls=':')
    a.set_title('Strength of scattering (rho)'); a.set_xlabel('rho'); a.set_ylabel('cases'); a.legend(fontsize=8)
    a = ax[1]
    a.scatter(col(LOW, 'ke'), col(LOW, 'rho'), c=cl, s=26, label='low')
    a.scatter(col(HIGH, 'ke'), col(HIGH, 'rho'), c=ch, s=26, label='high')
    a.axhline(1, color='k', ls=':'); a.set_xscale('log')
    a.set_xlabel('electron kinetic energy (eV, log)'); a.set_ylabel('rho'); a.set_title('rho against energy')
    a = ax[2]
    a.scatter(col(LOW, 'natoms'), col(LOW, 'rho'), c=cl, s=26)
    a.scatter(col(HIGH, 'natoms'), col(HIGH, 'rho'), c=ch, s=26)
    a.axhline(1, color='k', ls=':'); a.set_xlabel('atoms in the cluster'); a.set_ylabel('rho')
    a.set_title('rho against cluster size')
    fig.suptitle('Test set: %d cases. Red: strong scatterers (rho > 1); blue: weak scatterers (rho < 1).' % len(ROWS), fontsize=11)
    fig.tight_layout()
    fig.savefig(path, dpi=150)


if __name__ == '__main__':
    (ROOT / 'manuscript' / 'numbers_p100.tex').write_text('\n'.join(numbers()) + '\n')
    figure(ROOT / 'figures' / 'p100_test_set.png')
    print('wrote manuscript/numbers_p100.tex and figures/p100_test_set.png')
