C     Finite-order diagnostic: exact orders 0--2, Bernoulli higher paths.
      MODULE PATH_SAMPLING_MOD
      IMPLICIT NONE
      LOGICAL, SAVE :: MC_ENABLED=.FALSE.
      DOUBLE PRECISION, SAVE :: MC_PROB=1.D0
      INTEGER*8, SAVE :: MC_STATE=20261001_8
      INTEGER*8, SAVE :: MC_SEEN=0_8,MC_KEPT=0_8
      CONTAINS

      SUBROUTINE INIT_PATH_SAMPLING()
      USE APPROX_MOD, ONLY: IPW
      USE TESTS_MOD, ONLY: NPATHP
      USE RENORM_MOD, ONLY: I_REN
      CHARACTER*64 SETTING
      INTEGER ISTAT,ILEN,IOS
      MC_ENABLED=.FALSE.
      MC_SEEN=0_8
      MC_KEPT=0_8
      CALL GET_ENVIRONMENT_VARIABLE('MSSPEC_PATH_SAMPLE_P',SETTING,
     &                             LENGTH=ILEN,STATUS=ISTAT)
      IF(ISTAT.EQ.1.OR.ILEN.EQ.0) RETURN
      IF(ISTAT.NE.0) STOP 91
      READ(SETTING,*,IOSTAT=IOS) MC_PROB
      IF(IOS.NE.0) STOP 92
      IF(.NOT.(MC_PROB.GT.0.D0.AND.MC_PROB.LE.1.D0)) STOP 93
C     Adaptive intensity filters would change with stochastic weighting.
      IF(IPW.NE.0.OR.NPATHP.NE.0.OR.I_REN.NE.0) STOP 94
      MC_STATE=20261001_8
      CALL GET_ENVIRONMENT_VARIABLE('MSSPEC_PATH_SAMPLE_SEED',SETTING,
     &                             LENGTH=ILEN,STATUS=ISTAT)
      IF(ISTAT.EQ.0.AND.ILEN.GT.0) THEN
        READ(SETTING,*,IOSTAT=IOS) MC_STATE
        IF(IOS.NE.0) STOP 95
      ELSEIF(ISTAT.NE.1.AND.ILEN.NE.0) THEN
        STOP 96
      ENDIF
      IF(MC_STATE.LT.1_8.OR.MC_STATE.GE.2147483647_8) STOP 97
      MC_ENABLED=.TRUE.
      WRITE(*,*) 'PATH SAMPLING FINITE TAIL P=',MC_PROB
      END SUBROUTINE INIT_PATH_SAMPLING

      SUBROUTINE SAMPLE_PATH(ORDER,WEIGHT,SKIP)
      INTEGER, INTENT(IN) :: ORDER
      DOUBLE PRECISION, INTENT(OUT) :: WEIGHT
      LOGICAL, INTENT(OUT) :: SKIP
      WEIGHT=1.D0
      SKIP=.FALSE.
      IF(.NOT.MC_ENABLED.OR.ORDER.LE.2) RETURN
      MC_SEEN=MC_SEEN+1_8
      IF(MC_PROB.LT.1.D0) THEN
C       A local generator keeps sampling independent of global RNG state.
        MC_STATE=MOD(MC_STATE*48271_8,2147483647_8)
        IF(DBLE(MC_STATE)/2147483647.D0.GE.MC_PROB) THEN
          SKIP=.TRUE.
          RETURN
        ENDIF
      ENDIF
      MC_KEPT=MC_KEPT+1_8
      WEIGHT=1.D0/MC_PROB
      END SUBROUTINE SAMPLE_PATH

      SUBROUTINE PATH_SAMPLING_SUMMARY()
      IF(MC_ENABLED) THEN
        WRITE(*,*) 'PATH SAMPLING ELIGIBLE/KEPT:',MC_SEEN,MC_KEPT
      ENDIF
      END SUBROUTINE PATH_SAMPLING_SUMMARY
      END MODULE PATH_SAMPLING_MOD
